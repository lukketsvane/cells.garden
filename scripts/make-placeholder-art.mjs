#!/usr/bin/env node
// Generates placeholder pixel art for the plant parts that have no real
// sprites yet: roots, minerals and seeds. Without them three of the five zones
// render invisibly. The art is procedural and seeded, so re-running the script
// reproduces the same bytes. No dependencies: the PNG encoder is the one from
// scripts/make-icons.mjs, on top of node:zlib. Run with "npm run art:placeholders".
//
// These are stand-ins until real art lands. Every file name starts with
// "placeholder_" and every PNG carries a tEXt comment saying so. To replace
// them, drop real PNGs into the same folders (any file name; assets.ts picks
// from whatever the folder holds) and delete the placeholders.
//
// Outputs, in the shared category folders src/core/assets.ts reads:
//   src/assets/pack/roots/placeholder_root_N.png        35x8  thin branching strokes hanging from the top
//   src/assets/pack/minerals/placeholder_mineral_N.png  12x8  small gem clusters
//   src/assets/pack/seeds/placeholder_seed_N.png        9x9   a dark bulb with a highlight
//
// Scale: stems are 35x7 source px, drawn at PIXEL_SCALE 4 and stacked 6 source
// px apart (FIXED_STACK_STEP in src/core/model.ts). Underground parts are
// aligned top centre, so a root starts at row 0 where it meets the seed above
// it, and an 8 px tall root overlaps the next part by 2 px, much like a stem.
// Pass --show to print each sprite as text.

import { deflateSync } from 'node:zlib';
import { mkdirSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PACK = join(ROOT, 'src', 'assets', 'pack');
const SHOW = process.argv.includes('--show');
const COMMENT = 'Placeholder art generated by scripts/make-placeholder-art.mjs. Replace with real art.';

// Sprite geometry, mirroring src/core/model.ts and the plant_1 stems.
const STEM_WIDTH = 35; // STEM_ORIGIN_WIDTH
const TRUNK_X = 17; // the plant_1 stem trunk sits in columns 16..18, filled at 17

// Palette. The soil tile is near black (#1d2124), so the browns stay light
// enough to read on it, and the outline of the stems (#112316) would not.
const ROOT_COLORS = { dark: '#4a3421', mid: '#7a5533', light: '#a97c50' };
const SEED_COLORS = { outline: '#3b2616', body: '#6b4526', highlight: '#d4a86b' };
const GEM_PALETTES = [
    { base: '#5b3d9e', light: '#8f6ad8', highlight: '#e6d9ff' }, // amethyst
    { base: '#1f7a6e', light: '#3fb8a5', highlight: '#d2fff5' }, // teal
    { base: '#a5651a', light: '#e0a23a', highlight: '#fff0c2' }, // amber
    { base: '#a83a5e', light: '#e06a90', highlight: '#ffe0eb' }, // rose
];

// ---------------------------------------------------------------------------
// Seeded randomness (mulberry32) and a tiny pixel canvas.
// ---------------------------------------------------------------------------

function prng(seed) {
    let a = seed >>> 0;
    return () => {
        a = (a + 0x6d2b79f5) >>> 0;
        let t = a;
        t = Math.imul(t ^ (t >>> 15), t | 1);
        t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
        return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
}

/** Integer in [lo, hi], both inclusive. */
function between(rng, lo, hi) {
    return lo + Math.floor(rng() * (hi - lo + 1));
}

class Canvas {
    constructor(width, height) {
        this.width = width;
        this.height = height;
        this.pixels = new Array(width * height).fill(null);
    }

    inside(x, y) {
        return x >= 0 && y >= 0 && x < this.width && y < this.height;
    }

    /** Out-of-bounds writes are dropped, so strokes may wander off the edge. */
    set(x, y, hex) {
        if (this.inside(x, y)) this.pixels[y * this.width + x] = hex;
    }

    get(x, y) {
        return this.inside(x, y) ? this.pixels[y * this.width + x] : null;
    }

    toRgba() {
        const rgba = Buffer.alloc(this.width * this.height * 4);
        this.pixels.forEach((hex, i) => {
            if (!hex) return;
            const n = parseInt(hex.slice(1), 16);
            rgba[i * 4] = (n >> 16) & 0xff;
            rgba[i * 4 + 1] = (n >> 8) & 0xff;
            rgba[i * 4 + 2] = n & 0xff;
            rgba[i * 4 + 3] = 255;
        });
        return rgba;
    }

    toText() {
        const keys = [...new Set(this.pixels.filter(Boolean))];
        const rows = [];
        for (let y = 0; y < this.height; y++) {
            let row = '';
            for (let x = 0; x < this.width; x++) {
                const hex = this.get(x, y);
                row += hex ? String.fromCharCode(97 + keys.indexOf(hex)) : '.';
            }
            rows.push(row);
        }
        return rows.join('\n');
    }
}

// ---------------------------------------------------------------------------
// Roots: a taproot straight down from the seed, laterals wandering outwards.
// ---------------------------------------------------------------------------

function drawRoot(rng) {
    const c = new Canvas(STEM_WIDTH, 8);

    const depth = between(rng, 5, 7);
    for (let y = 0; y <= depth; y++) c.set(TRUNK_X, y, y === depth ? ROOT_COLORS.dark : ROOT_COLORS.mid);
    c.set(TRUNK_X, 1, ROOT_COLORS.light);

    const laterals = between(rng, 2, 4);
    for (let i = 0; i < laterals; i++) {
        const side = i % 2 === 0 ? 1 : -1;
        let x = TRUNK_X + side;
        let y = between(rng, 1, 3);
        const length = between(rng, 5, 13);
        let tail = 2; // steps a stroke may run along the bottom row before it ends
        for (let step = 0; step < length && tail > 0; step++) {
            c.set(x, y, step < 2 ? ROOT_COLORS.mid : ROOT_COLORS.dark);
            if (step > 2 && rng() < 0.2) drawRootlet(c, rng, x, y, side);
            x += side;
            if (y === c.height - 1) tail--;
            else if (rng() < 0.55) y++;
        }
    }
    return c;
}

/** A short hair off a lateral, going down and a little outwards. */
function drawRootlet(c, rng, x, y, side) {
    const length = between(rng, 1, 3);
    for (let step = 1; step <= length; step++) {
        y++;
        if (rng() < 0.5) x += side;
        c.set(x, y, ROOT_COLORS.dark);
    }
}

// ---------------------------------------------------------------------------
// Minerals: two or three crystals standing on the bottom row, plus loose shards.
// ---------------------------------------------------------------------------

function drawMineral(rng, palette) {
    const c = new Canvas(12, 8);
    const floor = c.height - 1;

    // Left edge of each 3 px crystal; the middle one is the tallest.
    const slots = [between(rng, 1, 3), between(rng, 4, 6), between(rng, 7, 9)];
    const chosen = between(rng, 2, 3) === 3 ? [0, 1, 2] : rng() < 0.5 ? [0, 1] : [1, 2];
    for (const i of chosen) {
        const height = i === 1 ? between(rng, 4, 6) : between(rng, 2, 4);
        drawCrystal(c, slots[i], height, palette);
    }

    const shards = between(rng, 1, 2);
    for (let i = 0; i < shards; i++) {
        const x = between(rng, 0, c.width - 1);
        if (!c.get(x, floor)) c.set(x, floor, palette.base);
    }
    return c;
}

/** Lit face on the left, shaded face on the right, a highlight on the tip. */
function drawCrystal(c, x0, height, palette) {
    const floor = c.height - 1;
    const top = floor - height + 1;
    for (let y = top + 1; y <= floor; y++) {
        c.set(x0, y, palette.light);
        c.set(x0 + 2, y, palette.base);
    }
    for (let y = top; y <= floor; y++) {
        c.set(x0 + 1, y, y === top ? palette.highlight : y < floor - Math.floor(height / 2) ? palette.light : palette.base);
    }
}

// ---------------------------------------------------------------------------
// Seeds: a bulb given by its row widths, outlined, with a highlight upper left.
// ---------------------------------------------------------------------------

const SEED_SHAPES = [
    [1, 3, 5, 7, 7, 7, 5, 3, 1], // round
    [3, 5, 7, 7, 7, 5, 5, 3, 1], // teardrop, point down
    [1, 3, 5, 5, 7, 7, 7, 5, 3], // pear, heavier at the bottom
];

function drawSeed(rng, widths) {
    const c = new Canvas(9, 9);
    const cx = 4;
    widths.forEach((w, y) => {
        const half = (w - 1) / 2;
        for (let x = cx - half; x <= cx + half; x++) c.set(x, y, SEED_COLORS.body);
    });
    // Outline: any body pixel touching transparency on one of its four sides.
    const edge = [];
    for (let y = 0; y < c.height; y++) {
        for (let x = 0; x < c.width; x++) {
            if (!c.get(x, y)) continue;
            if (!c.get(x - 1, y) || !c.get(x + 1, y) || !c.get(x, y - 1) || !c.get(x, y + 1)) edge.push([x, y]);
        }
    }
    for (const [x, y] of edge) c.set(x, y, SEED_COLORS.outline);

    const glint = (x, y) => { if (c.get(x, y) === SEED_COLORS.body) c.set(x, y, SEED_COLORS.highlight); };
    glint(cx - 1, 2);
    glint(cx - 1, 3);
    glint(cx - 2, between(rng, 3, 5));
    return c;
}

// ---------------------------------------------------------------------------
// PNG encoder: 8-bit RGBA, no interlace, filter type 0, plus a tEXt comment.
// ---------------------------------------------------------------------------

const CRC_TABLE = new Uint32Array(256);
for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    CRC_TABLE[n] = c >>> 0;
}

function crc32(buf) {
    let c = 0xffffffff;
    for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
    return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
    const typeBytes = Buffer.from(type, 'ascii');
    const length = Buffer.alloc(4);
    length.writeUInt32BE(data.length, 0);
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(crc32(Buffer.concat([typeBytes, data])), 0);
    return Buffer.concat([length, typeBytes, data, crc]);
}

function encodePng(width, height, rgba) {
    const signature = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

    const ihdr = Buffer.alloc(13);
    ihdr.writeUInt32BE(width, 0);
    ihdr.writeUInt32BE(height, 4);
    ihdr[8] = 8; // bit depth
    ihdr[9] = 6; // colour type: RGBA
    ihdr[10] = 0; // compression method
    ihdr[11] = 0; // filter method
    ihdr[12] = 0; // interlace method

    const stride = width * 4;
    const raw = Buffer.alloc((stride + 1) * height);
    for (let y = 0; y < height; y++) {
        raw[y * (stride + 1)] = 0; // filter type 0 (None)
        rgba.copy(raw, y * (stride + 1) + 1, y * stride, (y + 1) * stride);
    }

    const text = Buffer.concat([Buffer.from('Comment', 'latin1'), Buffer.from([0]), Buffer.from(COMMENT, 'latin1')]);

    return Buffer.concat([
        signature,
        chunk('IHDR', ihdr),
        chunk('tEXt', text),
        chunk('IDAT', deflateSync(raw, { level: 9 })),
        chunk('IEND', Buffer.alloc(0)),
    ]);
}

// ---------------------------------------------------------------------------
// Outputs. Each sprite has its own seed so adding a variant leaves the rest unchanged.
// ---------------------------------------------------------------------------

const jobs = [];
for (let i = 0; i < 4; i++) {
    jobs.push({ folder: 'roots', name: `placeholder_root_${i + 1}.png`, canvas: drawRoot(prng(0x100 + i)) });
}
for (let i = 0; i < GEM_PALETTES.length; i++) {
    jobs.push({ folder: 'minerals', name: `placeholder_mineral_${i + 1}.png`, canvas: drawMineral(prng(0x200 + i), GEM_PALETTES[i]) });
}
SEED_SHAPES.forEach((widths, i) => {
    jobs.push({ folder: 'seeds', name: `placeholder_seed_${i + 1}.png`, canvas: drawSeed(prng(0x300 + i), widths) });
});

// Clear stale placeholders first so a smaller set does not leave old files behind.
for (const folder of new Set(jobs.map(job => job.folder))) {
    const dir = join(PACK, folder);
    mkdirSync(dir, { recursive: true });
    for (const file of readdirSync(dir)) {
        if (/^placeholder_.*\.png$/.test(file)) unlinkSync(join(dir, file));
    }
}

for (const job of jobs) {
    const { canvas } = job;
    if (!canvas.pixels.some(Boolean)) throw new Error(`${job.name} is empty`);
    const png = encodePng(canvas.width, canvas.height, canvas.toRgba());
    const path = join(PACK, job.folder, job.name);
    writeFileSync(path, png);
    console.log(`${relative(ROOT, path)}  ${canvas.width}x${canvas.height}  ${png.length} bytes`);
    if (SHOW) console.log(canvas.toText().replace(/^/gm, '    '));
}
